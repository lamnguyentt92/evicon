        line = f"H-A1 ({name}) & K0 $\\to$ K0F, pp & {ci(v)}, {ok(v['pass'])}"
        if rp:
            w = rp["H-A1"]["policies"][pol]
            line += f" & {ci(w)}, {ok(w['pass'])}"
        L.append(line + " \\\\")
        key = "evAEvicon" if pol == "EVICON" else "evARes"
        N[key + "PP"], N[key + "Lo"], N[key + "Hi"] = num(v["effect_pp"]), num(v["ci95_pp"][0]), num(v["ci95_pp"][1])
