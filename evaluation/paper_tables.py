def fig_phase(report: Path, out: Path) -> str:
    """Release 073: clean fulfilment against the window W, simulator lines (EVICON) per contract, one panel
    per owner channel, with the testbed means (95 % t interval) of experiments W and S on top. Identity is
    carried by color, marker shape and (K2) a dashed line, with a legend; the caption says lines are the
    simulator's prediction and filled markers the testbed."""
    plt = _plt()
    src = report / "predict" / "predict.json"
    if plt is None or not src.exists():
        return "fig_phase.pdf: skipped" + (" (matplotlib missing)" if plt is None else " (no predict/predict.json)")
    r = json.loads(src.read_text())
    if not r.get("curves"):
        return "fig_phase.pdf: skipped (no simulator curves)"
    from matplotlib.lines import Line2D
    series = [("sim-k0", "K0", BLUE, "o", "-"), ("sim-k0+F", "K0F (fence)", ORANGE, "s", "-"), ("sim-k0+QS", "K0S (stop)", AQUA, "^", "-"),
              ("sim-k2", "K2 (dedup + query)", YELLOW, "D", "--")]
    testbed = {"K0": "sim-k0", "K0F": "sim-k0+F", "K0S": "sim-k0+QS", "K2": "sim-k2"}
    ws = sorted({p[0] for ch in r["curves"].values() for v in ch.values() for p in v})
    pos = {w: i for i, w in enumerate(ws)}
    labels = ["$\\infty$" if w >= 1000000 else str(w) for w in ws]
    fig, axes = plt.subplots(1, 2, figsize=(5.4, 2.5), sharey=True)
    rows = ["channel,series,w,source,clean_pct,lo,hi"]
    for ax, ch in zip(axes, ("queue", "direct")):
        cur = r["curves"].get(ch, {})
        for key, label, color, marker, ls in series:
            pts = cur.get(key)
            if not pts:
                continue
            ax.plot([pos[p[0]] for p in pts], [p[1] for p in pts], ls, color=color, lw=1.6, marker=marker, ms=3.5, mfc="white",
                    mec=color, mew=1.0, zorder=2)
            rows += [f"{ch},{key},{p[0]},sim,{p[1]},," for p in pts]
        for x in r["levels"]:
            run = x["run"].split("/")[0]
            if x["policy"] != "EVICON" or x["contract"] not in testbed or x["approximate"] or not run.startswith(("expW", "expS")):
                continue
            if (ch == "queue") != ("direct" not in run):
                continue
            w = 6 if run.endswith("w6") else max(ws)
            k = testbed[x["contract"]]
            color, marker = next((c, m) for kk, _, c, m, _ in series if kk == k)
            t, m = x["clean_pp_t95"], x["clean_pp_testbed"]
            off = {"expW": -0.14, "expS": 0.14}[run[:4]]
            ax.errorbar(pos[w] + off, m, yerr=[[m - t[0]], [t[1] - m]] if t else None, fmt=marker, ms=5.5, color=color, mec="white",
                        mew=0.8, ecolor=color, elinewidth=1.4, capsize=0, zorder=3)
            rows.append(f"{ch},{x['contract']},{w},testbed {run},{m},{t[0] if t else ''},{t[1] if t else ''}")
        ax.set_xticks(range(len(ws)))
        ax.set_xticklabels(labels)
        ax.set_xlim(-0.4, len(ws) - 0.6)
        ax.set_xlabel("window $W$ (unresolved commands)")
        ax.set_title(f"{ch} channel", loc="left")
        ax.grid(axis="y", color="#e6e5e0", lw=0.6)
        ax.set_axisbelow(True)
    axes[0].set_ylabel("clean fulfilment (% of offered)")
    axes[0].set_ylim(0, 85)
    handles = [Line2D([], [], color=c, ls=ls, lw=1.6, marker=m, ms=3.5, mfc="white", mec=c, label=lab) for _, lab, c, m, ls in series]
    handles.append(Line2D([], [], color=MUTED, ls="none", marker="o", ms=5.5, label="testbed, 95% CI"))
    fig.legend(handles=handles, loc="lower center", ncol=5, frameon=False, bbox_to_anchor=(0.5, 0.0), handlelength=1.8, columnspacing=1.0)
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(out / "fig_phase.pdf")
    plt.close(fig)
    (out / "fig_phase_data.csv").write_text("\n".join(rows) + "\n")
    return "fig_phase.pdf (data: fig_phase_data.csv)"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", required=True, help="the report directory written by `evicon_review.py report`")
    ap.add_argument("--out", default="", help="default: <report>/paper")
    a = ap.parse_args(argv)
    report = Path(a.report)
    out = Path(a.out) if a.out else report / "paper"
    out.mkdir(parents=True, exist_ok=True)
    N: dict = {}
    done = []
    if (report / "contract_map.csv").exists():
        done.append(contract_map(report, out, N))
    for step in (expA, cadence, pairs, latency, t3, predict, expC, expC2, expC3, safety, rq4, fence_cost, footprint, fig_expA, fig_rq4, fig_phase):
        done.append(step(report, out, N) if step not in (fig_expA, fig_rq4, fig_phase) else step(report, out))
    tl = report / "timeline" / "timeline.pdf"
    if tl.exists():
        shutil.copy2(tl, out / "fig_timeline.pdf")
        done.append("fig_timeline.pdf (copied from timeline/timeline.pdf)")
    bad = [k for k in N if not re.fullmatch(r"[A-Za-z]+", k)]
    if bad:
        raise SystemExit(f"macro names must be letters only: {bad}")
    (out / "numbers.json").write_text(json.dumps(N, indent=2, sort_keys=True) + "\n")
    (out / "numbers.tex").write_text(HEADER.format(src="the files of this report") + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(N.items())))
    (out / "README.md").write_text("# Paper tables and figures\n\nGenerated by `evaluation/paper_tables.py` from the report in the "
                                   "parent directory. Regenerate with `python3 evicon_review.py report`; do not edit.\n\n"
                                   + "".join(f"- {d}\n" for d in done) + f"- numbers.tex: {len(N)} macros (also numbers.json)\n")
    print(f"paper tables: {len([d for d in done if 'skipped' not in d])} files, {len(N)} numbers -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
