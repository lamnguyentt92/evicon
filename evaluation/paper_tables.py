DIGITS = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")


def macro_id(s: str) -> str:
    """'H-W1' -> 'HWOne': letters only, as LaTeX macro names need."""
    return "".join(DIGITS[int(c)] if c.isdigit() else c for c in str(s) if c.isalnum())


