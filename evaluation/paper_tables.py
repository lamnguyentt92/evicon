def tex(s) -> str:
    """Escapes text for LaTeX (not for strings that already carry LaTeX)."""
    s = str(s)
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"),
                 ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")):
        s = s.replace(a, b)
    return s.replace("≥", "$\\geq$").replace("✓", "\\checkmark").replace("—", "--").replace("∞", "$\\infty$")


def _round(x, nd):
    v = round(float(x), nd)
    return 0.0 if v == 0 else v  # no "-0.0"


def num(x, nd=1) -> str:
    """Plain number; a negative one carries \\ensuremath{-} so it reads right in text and in math."""
    try:
        v = _round(x, nd)
    except (TypeError, ValueError):
        return "--"
    return f"\\ensuremath{{-}}{-v:.{nd}f}" if v < 0 else f"{v:.{nd}f}"


def signed(x, nd=1) -> str:
    try:
        v = _round(x, nd)
    except (TypeError, ValueError):
        return "--"
    return f"$-${-v:.{nd}f}" if v < 0 else f"{v:+.{nd}f}"


def short_name(r: dict) -> tuple:
    for prefix, system, op in SHORT:
        if r["id"].startswith(prefix):
            if op is None:  # CoAP: the identity level is in the system name of the measurement
                op = "CON POST, " + ("message identity" if "identity=message" in r["system"] else "application identity")
            return system, op
    return tex(r["system"]), tex(r["operation"])


def seconds(x) -> str:
    v = float(x)
    return f"{v:.1f}".rstrip("0").rstrip(".") if v < 100 else f"{v:.0f}" if v == int(v) else f"{v:.1f}"


def contract_map(report: Path, out: Path, N: dict) -> str:
    src = report / "contract_map.csv"
    with open(src, newline="") as fh:
        rs = [r for r in csv.DictReader(fh) if r["source"] == "MEASURED"]
    ids = [r["id"] for r in rs]
    dropped = [r["id"] for r in rs for old, new in SUPERSEDED.items() if r["id"].startswith(old) and any(i.startswith(new) for i in ids)]
    rs = [r for r in rs if r["id"] not in dropped]
    rows, systems, releases = [], set(), set()
    for r in rs:
        system, op = short_name(r)
        systems.add(system)
        m = re.search(r"release (\d+)", r.get("measured_in", ""))
        if m:
            releases.add(m.group(1))
        cells = []
        for c in CAPS:
            v = r.get(c, "—")
            if c == "D_h" and v not in ("—", ""):
                lo, hi = r.get("D_h_lower_s", ""), r.get("D_h_upper_s", "")
                v = (f"[{seconds(lo)}, {seconds(hi)})\\,s" if lo != "" and hi != "" else
                     f"$\\geq${seconds(lo)}\\,s" if lo != "" else tex(v))
            elif c == "T" and v not in ("—", ""):
                m = re.fullmatch(r"([\d.]+)s", v)
                v = f"{seconds(m.group(1))}\\,s" if m else tex(v)
            else:
                v = tex(v)
            cells.append(v)
        rows.append((system, op, r["level"], r.get("declared_level", "") or "--", cells))
    rows.sort(key=lambda x: (x[0].lower(), x[1]))
    L = [HEADER.format(src="report/contract_map.csv (measured rows)"),
         "\\begin{tabular}{llcc" + "c" * len(CAPS) + "}", "\\toprule",
         "System & Use of the API & Measured & Declared & " + " & ".join(CAP_TEX[c] for c in CAPS) + " \\\\", "\\midrule"]
    prev = None
    for system, op, lvl, dec, cells in rows:
        L.append(f"{system if system != prev else ''} & {op} & {lvl} & {dec} & " + " & ".join(cells) + " \\\\")
        prev = system
    L += ["\\bottomrule", "\\end{tabular}", ""]
    (out / "tab_contract_map.tex").write_text("\n".join(L))
    N["evSystems"] = str(len(systems))
    N["evThirdPartySystems"] = str(len([x for x in systems if x not in OWN_SYSTEMS]))  # release 083
    N["evConfigs"] = str(len(rows))
    N["evMeasuredReleases"] = ", ".join(sorted(releases)) or "--"
    return (f"tab_contract_map.tex: {len(rows)} measured configurations of {len(systems)} systems"
            + (f" (superseded by a later measurement of the same firmware, left out: {', '.join(dropped)})" if dropped else ""))


def k2_077(report: Path) -> dict:
    """Release 081, the rule of PREREG_review_077.md for K-1, K-2: MET -> experiment A's K2 result holds on the
    release-077 runtime; NOT MET -> the paper reports the replication instead of experiment A's K2 numbers.
    Returns {policy: hypothesis} when both are decided and not both MET (the replication replaces A's K2 rows),
    else {}."""
    src = report / "pairs" / "PREREG_review_077" / "results.json"
    if not src.exists():
        return {}
    hs = {h["id"]: h for h in json.loads(src.read_text()).get("hypotheses", []) if h.get("id") in ("K-1", "K-2")}
    if set(hs) != {"K-1", "K-2"} or not all(h.get("n") for h in hs.values()):
        return {}
    if all(h.get("verdict") == "MET" for h in hs.values()):
        return {}
    return {h["spec"]["policy"]: h for h in hs.values()}


