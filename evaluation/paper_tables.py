def _rq4_rows(report: Path) -> list:
    src = report / "overhead" / "overhead.json"
    if not src.exists():
        return []
    rows = json.loads(src.read_text())
    out = []
    for r in rows:
        base = r["campaign"].split("@")[0]
        if base in LOADS:
            out.append(dict(r, per_device=LOADS[base]))
    return sorted(out, key=lambda r: (r["per_device"], r["contract"], r["policy"]))


def authority_ms(r, p=50):
    parts = [r.get(f"lock_ms_p{p}"), r.get(f"eval_ms_p{p}"), r.get(f"decide_ms_p{p}")]
    return None if any(x is None for x in parts) else sum(parts)


def rq4(report: Path, out: Path, N: dict) -> str:
    rows = _rq4_rows(report)
    if not rows:
        return "tab_rq4_overhead.tex: skipped (no RQ4 rows in overhead/overhead.json)"
    L = [HEADER.format(src="report/overhead/overhead.json (rq4-load-r*)"),
         "\\begin{tabular}{rllrrrrrrr}", "\\toprule",
         "Load & Contract & Policy & Client p50 & \\multicolumn{3}{c}{Authority p50 (ms)} & CPU & RSS & Journal \\\\",
         "\\cmidrule(lr){5-7}",
         "(cmd/s) & & & (ms) & lock & eval & commit & (\\%) & (MB) & (B/cmd) \\\\", "\\midrule"]
    prev = None
    for r in rows:
        load = f"{r['offered_per_s']:.0f}" if r["per_device"] != prev else ""
        if prev is not None and r["per_device"] != prev:
            L.append("\\addlinespace")
        prev = r["per_device"]
        L.append(f"{load} & {r['contract']} & {POLICY.get(r['policy'], tex(r['policy']))} & {num(r.get('client_ms_p50'))} & {num(r.get('lock_ms_p50'), 2)} & "
                 f"{num(r.get('eval_ms_p50'))} & {num(r.get('decide_ms_p50'))} & {num(r.get('authority_cpu_pct_mean'))} & "
                 f"{num(r.get('authority_rss_mb_max'))} & {num(r.get('db_bytes_per_cmd'), 0)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", ""]
    (out / "tab_rq4_overhead.tex").write_text("\n".join(L))
    auth = [authority_ms(r) for r in rows if authority_ms(r) is not None]
    if auth:
        N["evAuthMinMs"], N["evAuthMaxMs"] = num(min(auth)), num(max(auth))
    hi = [r for r in rows if r["per_device"] == max(x["per_device"] for x in rows)]
    lo = [r for r in rows if r["per_device"] == min(x["per_device"] for x in rows)]
    N["evLoadMax"] = f"{max(r['offered_per_s'] for r in rows):.0f}"
    N["evCpuMax"] = num(max(r.get("authority_cpu_pct_mean") or 0 for r in rows))
    N["evRssMax"] = num(max(r.get("authority_rss_mb_max") or 0 for r in rows))
    N["evJournalMin"] = num(min(r.get("db_bytes_per_cmd") or 0 for r in rows), 0)
    N["evJournalMax"] = num(max(r.get("db_bytes_per_cmd") or 0 for r in rows), 0)
    cl = [r.get("client_ms_p50") for r in hi if r.get("client_ms_p50") is not None]
    if cl:
        N["evClientHighMs"] = num(max(cl), 0)
    cl = [r.get("client_ms_p50") for r in lo if r.get("client_ms_p50") is not None]
    if cl:
        N["evClientLowMinMs"], N["evClientLowMaxMs"] = num(min(cl), 0), num(max(cl), 0)
    ev = [r.get("events_per_cmd") for r in rows if r.get("events_per_cmd") is not None]
    if ev:
        N["evEventsPerCmd"] = num(sum(ev) / len(ev))
    return f"tab_rq4_overhead.tex: {len(rows)} load groups"


def fence_cost(report: Path, out: Path, N: dict) -> str:
    src = report / "overhead" / "overhead.json"
    if not src.exists():
        return "tab_fence_cost.tex: skipped"
    rows = [r for r in json.loads(src.read_text()) if r["campaign"].startswith(("expA-confirm", "expB2-cadence"))
            and r.get("fences_per_cmd") and r["policy"] in ("EVICON", "RES_PERIODIC")]
    if not rows:
        return "tab_fence_cost.tex: skipped (no fences in the confirmatory campaigns)"
    roles = {}
    cj = report / "confirm_expA" / "results.json"
    if cj.exists():  # which run is the preregistered one and which are replications
        c = json.loads(cj.read_text())
        roles[c.get("k0_run", "").split("/")[-1]] = "K0 config, preregistered"
        roles[c.get("k2_run", "").split("/")[-1]] = "K2 config, preregistered"
        for x in (c.get("post_hoc", {}).get("replications") or {}).get("runs", []):
            roles[x["run"].split("/")[-1]] = "K0 config, replication"

    prereg = {v.split(" config")[0]: k for k, v in roles.items() if v.endswith("preregistered") and k}

    def role(r):
        camp, _, stamp = r["campaign"].partition("@")
        if stamp in roles:
            return roles[stamp]
        cfg = {"expA-confirm-k0": "K0", "expA-confirm-k2": "K2"}.get(camp)
        if cfg and stamp and prereg.get(cfg) and stamp != prereg[cfg]:
            # release 083 (OPEN_ITEMS (a) 6): another run of a confirmatory config than its preregistered one is a
            # replication (the 072 K2 replication was labelled "preregistered" too)
            return f"{cfg} config, replication"
        # one run of the campaign only (no @stamp in its label): the preregistered one
        return {"expA-confirm-k0": "K0 config, preregistered", "expA-confirm-k2": "K2 config, preregistered",
                "expB2-cadence": "B2, both at 10\\,s"}.get(camp, tex(r["campaign"]))
    rows.sort(key=lambda r: (r["campaign"], r["contract"], r["policy"]))
    L = [HEADER.format(src="report/overhead/overhead.json (expA-confirm-*)"),
         "\\begin{tabular}{lllrrrrr}", "\\toprule",
         "Run & Contract & Policy & Fences & \\multicolumn{3}{c}{Domain pause} & Paused \\\\", "\\cmidrule(lr){5-7}",
         " & & & per command & p50 (ms) & p95 (s) & max (s) & (\\% of time) \\\\", "\\midrule"]
    for r in rows:
        L.append(f"{role(r)} & {r['contract']} & {POLICY.get(r['policy'], tex(r['policy']))} & {num(r['fences_per_cmd'], 3)} & "
                 f"{num(r.get('fence_pause_ms_p50'))} & {num((r.get('fence_pause_ms_p95') or 0) / 1000)} & "
                 f"{num((r.get('fence_pause_ms_max') or 0) / 1000)} & {num(100 * (r.get('paused_fraction') or 0))} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", ""]
    (out / "tab_fence_cost.tex").write_text("\n".join(L))
    k0f = [r for r in rows if r["contract"] == "K0F" and r["policy"] == "EVICON"]
