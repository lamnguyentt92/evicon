#!/usr/bin/env python3
"""Results records of the preregistered plans (release 075).

Each preregistered plan in evaluation/prereg is frozen and never edited after its run. Its outcome is
recorded next to it, in a separate file, from the report of a review run (`evicon_review.py report`):

  RESULTS_<plan>.md   a header naming the result bundle (file name and SHA-256) and the review run, the
                      analysis exactly as pairs_report.py (plans with a pairs-spec) or cadence_report.py
                      (experiment B2) wrote it into the report, the plan's own Deviations section, and,
                      when a note exists in evaluation/prereg/notes/<plan>.md, the interpretation written
                      after the run (marked as such: it is not part of the plan)

The analysis is copied, not recomputed: the record shows what the frozen analysis printed. Regenerate with

    python3 evaluation/results_record.py --report <report dir> --bundle <result zip> [--out evaluation/prereg]

Plans already recorded by their own report script (RESULTS_expA_confirm_067.md, confirm_report.py) are
left alone.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CADENCE_PLAN = "PREREG_expB2_cadence_071"


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def record_name(stem: str) -> str:
    return "RESULTS_" + (stem[len("PREREG_"):] if stem.startswith("PREREG_") else stem[len("PLAN_"):] if stem.startswith("PLAN_") else stem) + ".md"


def deviations(plan: Path) -> str:
    m = re.search(r"^## Deviations\s*\n(.*)\Z", plan.read_text(), re.S | re.M)
    return m.group(1).strip() if m else "(the plan has no Deviations section)"


def title(plan: Path) -> str:
    first = plan.read_text().splitlines()[0]
    t = re.sub(r"^#\s*(Preregistration:\s*|Plan:\s*)?", "", first).strip()
    return t[:1].upper() + t[1:]


def record(stem: str, analysis: Path, rel: str, bundle: Path, bundle_sha: str, review: str, prereg: Path, notes: Path) -> str:
    plan = prereg / f"{stem}.md"
    body = analysis.read_text().strip().splitlines()
    if body and body[0].startswith("# "):  # the analysis' own title becomes a section
        body[0] = "## Analysis (frozen script): " + re.sub(r"^Paired analysis:\s*", "", body[0][2:])
    body = [("#" + x if x.startswith("## ") and i > 0 else x) for i, x in enumerate(body)]
    rel = (REPO / "VERSION").read_text().strip() if (REPO / "VERSION").exists() else "?"
    L = [f"<!-- Generated by evaluation/results_record.py (release {rel}) from {bundle.name} (SHA-256 {bundle_sha}), run {review}. "
         f"The frozen plan {stem}.md (SHA-256 {sha256(plan)}) is unchanged; this file records its outcome. -->", "",
         f"# {title(plan)}: results", "",
         f"Plan: `evaluation/prereg/{stem}.md` (frozen before the run; the driver verified its SHA-256 and frozen files before the campaign, "
         f"and the analysis below verified them again). Result bundle `{bundle.name}`, SHA-256 `{bundle_sha}`; review run `{review}`. "
         f"The analysis below is copied unchanged from `report/{rel}` of that run.", ""]
    L += body
    L += ["", "## Deviations (from the plan)", "", deviations(plan)]
    n = notes / f"{stem}.md"
    if n.exists():
        L += ["", "## Interpretation (written after the run; not part of the plan)", "", n.read_text().strip()]
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", required=True)
    ap.add_argument("--bundle", required=True)
    ap.add_argument("--out", default=str(REPO / "evaluation" / "prereg"))
    ap.add_argument("--notes", default=str(REPO / "evaluation" / "prereg" / "notes"))
    a = ap.parse_args(argv)
    report, bundle, out = Path(a.report), Path(a.bundle), Path(a.out)
    prereg = REPO / "evaluation" / "prereg"
    bsha = sha256(bundle)
    review = report.parent.name
    todo = [(p.parent.name, p, f"pairs/{p.parent.name}/RESULTS.md") for p in sorted((report / "pairs").glob("*/RESULTS.md"))]
    if (report / "cadence" / "RESULTS.md").exists():
        todo.append((CADENCE_PLAN, report / "cadence" / "RESULTS.md", "cadence/RESULTS.md"))
    written = []
    for stem, analysis, rel in todo:
        if not (prereg / f"{stem}.md").exists():
            print(f"results_record: no plan {stem}.md, skipped", file=sys.stderr)
            continue
        dest = out / record_name(stem)
        dest.write_text(record(stem, analysis, rel, bundle, bsha, review, prereg, Path(a.notes)))
        written.append(dest.name)
    print(f"results_record: {len(written)} records -> {out}: {', '.join(written)}")
    return 0 if written else 1


if __name__ == "__main__":
    sys.exit(main())
